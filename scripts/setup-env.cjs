const fs = require("node:fs")
const path = require("node:path")
const { randomBytes } = require("node:crypto")
const root = path.resolve(__dirname, "..")
const filename = path.join(root, ".env")
if (!fs.existsSync(filename)) {
  const database = randomBytes(24).toString("hex"), redis = randomBytes(24).toString("hex"), storage = randomBytes(24).toString("hex")
  let template = fs.readFileSync(path.join(root, ".env.template"), "utf8")
  template = template.replace(/^POSTGRES_PASSWORD=.*$/m, `POSTGRES_PASSWORD=${database}`).replace(/medusa_admin:CHANGE_ME@/g, `medusa_admin:${database}@`)
    .replace(/^REDIS_PASSWORD=.*$/m, `REDIS_PASSWORD=${redis}`).replace(/redis:\/\/:CHANGE_ME@/g, `redis://:${redis}@`)
    .replace(/^JWT_SECRET=.*$/m, `JWT_SECRET=${randomBytes(48).toString("hex")}`).replace(/^COOKIE_SECRET=.*$/m, `COOKIE_SECRET=${randomBytes(48).toString("hex")}`)
    .replace(/^MINIO_ROOT_PASSWORD=.*$/m, `MINIO_ROOT_PASSWORD=${storage}`).replace(/^S3_SECRET_KEY=.*$/m, `S3_SECRET_KEY=${storage}`)
  fs.writeFileSync(filename, template, { flag: "wx" })
}
const backend = path.join(root, "apps/backend/.env")
if (!fs.existsSync(backend)) fs.copyFileSync(filename, backend, fs.constants.COPYFILE_EXCL)
const storefront = path.join(root, "apps/storefront/.env.local")
if (!fs.existsSync(storefront)) fs.copyFileSync(path.join(root, "apps/storefront/.env.template"), storefront, fs.constants.COPYFILE_EXCL)
console.log("Local environment files are ready. Existing values were preserved. Configure your Medusa publishable key before using the storefront API.")
